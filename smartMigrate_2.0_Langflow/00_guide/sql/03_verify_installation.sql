-- Read-only checks. Run as target/management owner (TGT_NEW).
SET DEFINE OFF;
SELECT USER, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA FROM DUAL;

-- Expect 5 tables and 2 sequences. Indexes are listed separately below.
SELECT OBJECT_TYPE, OBJECT_NAME, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('NEXT_MIG_INFO', 'NEXT_MIG_INFO_DTL', 'NEXT_SQL_INFO',
                       'NEXT_MIG_RAG_INFO', 'NEXT_MIG_LOG',
                       'MIGRATION_LOG_SEQ', 'NEXT_SQL_INFO_SQL_SEQ')
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

-- Expect all 4 columns. MAP_ID in NEXT_MIG_LOG must be VARCHAR2.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'NEXT_SQL_INFO' AND COLUMN_NAME IN ('SQL_SEQ', 'REF_SEQ'))
    OR (TABLE_NAME = 'NEXT_MIG_INFO' AND COLUMN_NAME = 'VERIFY2_SQL')
    OR (TABLE_NAME = 'NEXT_MIG_LOG' AND COLUMN_NAME = 'MAP_ID')
 ORDER BY TABLE_NAME, COLUMN_NAME;

SELECT C.TABLE_NAME, C.CONSTRAINT_TYPE, CC.COLUMN_NAME, CC.POSITION
  FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC
    ON C.CONSTRAINT_NAME = CC.CONSTRAINT_NAME
 WHERE C.TABLE_NAME IN ('NEXT_MIG_INFO', 'NEXT_MIG_INFO_DTL', 'NEXT_SQL_INFO')
   AND C.CONSTRAINT_TYPE IN ('P', 'U')
 ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME, CC.POSITION;

SELECT TABLE_NAME, INDEX_NAME, STATUS FROM USER_INDEXES
 WHERE TABLE_NAME IN ('NEXT_MIG_INFO', 'NEXT_MIG_INFO_DTL', 'NEXT_SQL_INFO',
                      'NEXT_MIG_RAG_INFO', 'NEXT_MIG_LOG')
 ORDER BY TABLE_NAME, INDEX_NAME;

SELECT 'NEXT_MIG_INFO' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM NEXT_MIG_INFO
UNION ALL SELECT 'NEXT_MIG_INFO_DTL', COUNT(*) FROM NEXT_MIG_INFO_DTL
UNION ALL SELECT 'NEXT_SQL_INFO', COUNT(*) FROM NEXT_SQL_INFO
UNION ALL SELECT 'NEXT_MIG_RAG_INFO', COUNT(*) FROM NEXT_MIG_RAG_INFO
UNION ALL SELECT 'NEXT_MIG_LOG', COUNT(*) FROM NEXT_MIG_LOG;

-- Expect zero rows: details without a master.
SELECT D.MAP_ID, D.MAP_DTL FROM NEXT_MIG_INFO_DTL D
 WHERE NOT EXISTS (SELECT 1 FROM NEXT_MIG_INFO M WHERE M.MAP_ID = D.MAP_ID);

SELECT MAP_ID, STATUS, BATCH_CNT, RETRY_COUNT FROM NEXT_MIG_INFO ORDER BY MAP_ID;
SELECT SQL_SEQ, SPACE_NM, SQL_ID, STATUS_CONVERSION, STATUS_TUNING
  FROM NEXT_SQL_INFO ORDER BY SQL_SEQ;
SELECT * FROM (
    SELECT LOG_ID, CREATED_AT, MAP_ID, MIG_KIND, LOG_TYPE, STEP_NAME, STATUS,
           DBMS_LOB.SUBSTR(MESSAGE, 500, 1) AS MESSAGE_PREVIEW
      FROM NEXT_MIG_LOG ORDER BY LOG_ID DESC
) WHERE ROWNUM <= 30;
